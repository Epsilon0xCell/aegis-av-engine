"""Corpus property registry: the generators' claims, asserted.

Every generated corpus file makes a claim in its name or its
label: this one is high entropy, that one is clean, this one
carries a signature marker. v2 shipped a fixture whose name
claimed high entropy while its bytes were a single repeated
value, and the lie survived three releases because nothing
asserted the property. This registry is the assertion layer:
each property is a function over the generated bytes, the
checks run in the test suite and from the CLI, and a property
failure names the file and the claim it broke.
"""
from __future__ import annotations

from pathlib import Path

from . import corpora
from .formats import shannon_entropy


def _props_for(name: str, blob: bytes) -> list[tuple[str, bool, str]]:
    checks: list[tuple[str, bool, str]] = []
    if name == "fixture_high_entropy.bin":
        checks.append(("entropy above 7.0", shannon_entropy(blob) > 7.0,
                       f"measured {shannon_entropy(blob):.3f}"))
        checks.append(("more than 200 distinct byte values",
                       len(set(blob)) > 200, f"measured {len(set(blob))}"))
    if (name.startswith("fixture_") and name != "fixture_high_entropy.bin") \
            or name == "eicar_test_file.txt":
        # the high-entropy fixture's claim is its entropy, not a
        # marker; it is deliberately marker-free random bytes
        checks.append(("carries a fixture marker",
                       b"AEGIS-SYNTH" in blob or b"LAB-SYNTHETIC" in blob
                       or b"EICAR" in blob or b"INERT FIXTURE" in blob,
                       "no marker found"))
    return checks


def check_corpora(clean_dir: Path, fixture_dir: Path) -> list[dict]:
    failures: list[dict] = []
    for directory, is_fixture in ((clean_dir, False), (fixture_dir, True)):
        for path in sorted(Path(directory).rglob("*")):
            if not path.is_file():
                continue
            blob = path.read_bytes()
            for claim, ok, detail in _props_for(path.name, blob):
                if not ok:
                    failures.append({"file": str(path), "claim": claim,
                                     "detail": detail})
            if not is_fixture:
                if b"AEGIS-SYNTH" in blob or b"EICAR-STANDARD" in blob:
                    failures.append({"file": str(path),
                                     "claim": "clean file carries no "
                                              "fixture marker",
                                     "detail": "marker found in clean corpus"})
            if path.suffix in (".txt", ".md", ".json", ".csv", ".py"):
                ent = shannon_entropy(blob)
                if ent > 6.0:
                    failures.append({"file": str(path),
                                     "claim": "text-like file entropy "
                                              "below 6.0",
                                     "detail": f"measured {ent:.3f}"})
    return failures


def generate_and_check(root: Path) -> list[dict]:
    corpora.make_clean_corpus(root / "clean")
    corpora.make_fixture_corpus(root / "fixtures")
    return check_corpora(root / "clean", root / "fixtures")
