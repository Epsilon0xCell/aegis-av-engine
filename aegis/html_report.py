"""Single-file HTML scan reports.

One self-contained file: inline CSS, no scripts, no external
references, openable offline and safe to email. Every value
that came from a scanned file (names above all) is escaped
with html.escape before interpolation: a report about hostile
filenames must not become a host for them. The escaping
property is covered by a dedicated test with a script-tag
filename.
"""
from __future__ import annotations

import html
import json

_CSS = """
body { font-family: system-ui, sans-serif; margin: 2rem; color: #1a1a1a; }
table { border-collapse: collapse; width: 100%; }
th, td { border: 1px solid #ccc; padding: 0.35rem 0.5rem;
         text-align: left; font-size: 0.9rem; }
tr.malicious_pattern td.verdict { color: #a00; font-weight: 700; }
tr.suspicious td.verdict { color: #b06000; font-weight: 700; }
code { font-size: 0.8rem; word-break: break-all; }
details { margin: 0.25rem 0; }
"""


def _e(value) -> str:
    return html.escape(str(value), quote=True)


def render_report(report: dict, title: str = "Aegis scan report") -> str:
    summary = report.get("summary", {})
    rows = []
    for verdict in report.get("results", []):
        evidence = verdict.get("evidence", [])
        ev_html = "<br>".join(
            f"<code>{_e(json.dumps(e, default=str)[:300])}</code>"
            for e in evidence[:12])
        rows.append(
            f"<tr class=\"{_e(verdict.get('verdict', ''))}\">"
            f"<td>{_e(verdict.get('file', ''))}</td>"
            f"<td class=\"verdict\">{_e(verdict.get('verdict', ''))}</td>"
            f"<td>{_e(verdict.get('score', ''))}</td>"
            f"<td><code>{_e(verdict.get('hashes', {}).get('sha256', ''))}"
            f"</code></td>"
            f"<td><details><summary>{len(evidence)} entries</summary>"
            f"{ev_html}</details></td></tr>")
    counts = ", ".join(f"{_e(k)}: {_e(v)}" for k, v in
                       sorted(summary.items()))
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>{_e(title)}</title><style>{_CSS}</style></head>
<body><h1>{_e(title)}</h1>
<p>Root: {_e(report.get('root', ''))} &middot; Files: 
{_e(report.get('files', len(rows)))} &middot; {counts}</p>
<p>Generated by Aegis AV Engine. Verdicts cover this project's
synthetic fixture knowledge and heuristics; see BENCHMARK.md
for what the numbers do and do not mean.</p>
<table><tr><th>File</th><th>Verdict</th><th>Score</th>
<th>SHA-256</th><th>Evidence</th></tr>
{''.join(rows)}
</table></body></html>
"""
